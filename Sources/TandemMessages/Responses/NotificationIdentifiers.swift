import Foundation

/// Upstream's identifier for each notification id, and the pump firmware's own name for it where
/// Tandem's event schema gives one (pumpx2 ade579c0 and c7c8fe09: "Tandem firmware name" on each
/// enum constant). These are data for diagnostics and logs, not display text: the titles in each
/// response's `names` table stay the words the app shows. Generated from the pinned oracle's
/// `AlertResponseType`, `AlarmResponseType` and `CGMAlert`; `NotificationIdentifierParityTests`
/// checks every id against the oracle.
public struct NotificationIdentifier: Sendable, Equatable {
    /// Upstream's enum constant, e.g. `CARTRIDGE_ALARM_P2`.
    public let constant: String
    /// The firmware's name, e.g. `Alarm_P2`; nil where Tandem's schema doesn't give one.
    public let firmwareName: String?

    public init(_ constant: String, _ firmwareName: String?) {
        self.constant = constant
        self.firmwareName = firmwareName
    }
}

